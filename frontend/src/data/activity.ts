/* ---------------- Scheduled 6-hour cron syncs (deterministic, generated) ---------------- */

const SYNC_HOURS = [4, 10, 16, 22];
const pad = (n: number) => String(n).padStart(2, '0');

function buildSyncs(): ActivityEntry[] {
  const out: ActivityEntry[] = [];
  let i = 0;
  for (let day = 1; day <= 31; day++) {
    for (const hour of SYNC_HOURS) {
      if (day === 31 && hour > 10) continue; // the log ends at the Oct 31 10:18 run
      const date = `2024-10-${pad(day)}`;
      const timestamp = `${date}T${pad(hour)}:18:${pad(10 + ((i * 7) % 40))}`;
      const last = day === 31 && hour === 10;
      const duration = last ? 4.2 : 3.4 + ((i * 7) % 15) / 10;
      const media = 118 + Math.floor((day - 1) / 3);
      const comments = 140 + ((i * 37) % 180);
      const id = `EVT_SYNC_CRON_6H_${String(i + 1).padStart(3, '0')}`;
      out.push({
        id,
        timestamp,
        category: 'data_sync',
        kind: 'Data Sync',
        kindIcon: 'sync',
        kindTone: 'neutral',
        kindIconClass: 'text-tertiary',
        title: 'Scheduled Cron Ingestion',
        summary: `Scheduled 6-hour cron sync completed. Synced ${media} media assets, ${comments} new comments, and demographic metrics via Graph API v19.0.`,
        narrative: `Scheduled 6-hour cron sync completed for @ekoindia in ${duration.toFixed(1)} seconds: ${media} media assets refreshed, ${comments} new comments ingested and audience demographics updated (sample record — no live Graph API call is made in this prototype).`,
        target: { label: '@ekoindia (biz_948)', to: '/accounts/acc-ekoindia', module: 'Instagram account' },
        actorId: 'sys-graph-api',
        accountId: 'acc-ekoindia',
        outcome: 'success',
        outcomeLabel: last ? 'Success (4.2s)' : undefined,
        responseStatus: `200 OK (${duration.toFixed(1)}s)`,
        origin: INTERNAL,
        payload: {
          event_id: id,
          type: 'GRAPH_API_SCHEDULED_SYNC',
          account_id: 'ig_biz_9482710381',
          sync_stats: { media_count: media, comments_ingested: comments, duration_sec: Number(duration.toFixed(1)) },
          status: 200,
        },
      });
      i++;
    }
  }
  return out;
}

export const activityEntries: ActivityEntry[] = [...handcrafted, ...buildSyncs()].sort((a, b) => (a.timestamp < b.timestamp ? 1 : -1));
