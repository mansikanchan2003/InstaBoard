/* ------------------------------------------------------------------------------------------
 * Daily sentiment trajectory (Oct 1–31). Deterministic (fixed seed); each series sums to the
 * sentiment totals above. Positive volume peaks around Oct 22.
 * ---------------------------------------------------------------------------------------- */
function seeded(seed: number) {
  let s = seed;
  return () => {
    s = (s * 1664525 + 1013904223) % 4294967296;
    return s / 4294967296;
  };
}

function distribute(total: number, weights: number[]): number[] {
  const sum = weights.reduce((a, b) => a + b, 0);
  const raw = weights.map((w) => (w / sum) * total);
  const out = raw.map(Math.floor);
  let rest = total - out.reduce((a, b) => a + b, 0);
  const order = raw.map((v, i) => ({ i, frac: v - Math.floor(v) })).sort((a, b) => b.frac - a.frac);
  for (let k = 0; rest > 0; k++, rest--) out[order[k % order.length].i] += 1;
  return out;
}

function buildSentimentTrend(): SentimentTrendPoint[] {
  const rnd = seeded(97);
  const days = 31;
  const pos = Array.from({ length: days }, (_, i) => (1 + 0.9 * (i / 30)) * (1 + (rnd() - 0.5) * 0.2) + Math.exp(-((i + 1 - 22) ** 2) / 6) * 0.9);
  const neu = Array.from({ length: days }, (_, i) => (1 + 0.25 * (i / 30)) * (1 + (rnd() - 0.5) * 0.16));
  const neg = Array.from({ length: days }, (_, i) => (1 + 0.1 * Math.sin(i / 3)) * (1 + (rnd() - 0.5) * 0.24));
  const p = distribute(POSITIVE, pos);
  const n = distribute(NEUTRAL, neu);
  const g = distribute(NEGATIVE, neg);
  return p.map((v, i) => {
    const total = v + n[i] + g[i];
    const score = Math.round(((v * 100 + n[i] * 55 + g[i] * 10) / total) * 10) / 10;
    return { date: `Oct ${i + 1}`, positive: v, neutral: n[i], negative: g[i], score };
  });
}

