import { Badge } from '@/components/ui/Badge';
import { Icon } from '@/components/ui/Icon';
import { Notice } from '@/components/ui/Misc';
import { Skeleton } from '@/components/ui/States';
import { useQuery } from '@/hooks/useQuery';
import { formatNumber } from '@/lib/format';
import { aiService } from '@/services/ai';
import type { AIJob, EvidenceFact, InsightAI } from '@/types/ai';
import { aiStageLabel } from './useAiJob';

export const qualityMeta: Record<InsightAI['evidenceQuality'], { label: string; tone: 'active' | 'amber' | 'neutral'; help: string }> = {
  high: { label: 'Evidence: High', tone: 'active', help: 'All cited figures have enough data (≥ 10 observations, ≤ 10% missing).' },
  medium: { label: 'Evidence: Medium', tone: 'amber', help: 'Cited figures meet the minimum sample size but are small or have some missing values.' },
  low: { label: 'Evidence: Low', tone: 'neutral', help: 'At least one cited figure is based on insufficient data — treat as a weak signal.' },
};

const sourceLabel: Record<EvidenceFact['source'], string> = {
  demo_dataset: 'Demo dataset (stored in the database)',
  workspace_data: 'Workspace data',
  instagram_api: 'Instagram API (live)',
};

/** "AI-generated · model" label; makes clear the text is a model suggestion, not a completed action. */
export function AiGeneratedBadge({ ai }: { ai: Pick<InsightAI, 'model' | 'provider'> }) {
  return (
    <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-label-code font-label-code bg-ai-subtle border border-ai-border text-ai-accent" title={`Generated by ${ai.provider} · ${ai.model}`}>
      <Icon name="auto_awesome" filled className="text-[12px]" /> AI-generated · {ai.model}
    </span>
  );
}

export function QualityPill({ quality }: { quality: InsightAI['evidenceQuality'] }) {
  const meta = qualityMeta[quality];
  return <Badge tone={meta.tone} icon="fact_check"><span title={meta.help}>{meta.label}</span></Badge>;
}

export function AiJobProgress({ job }: { job: AIJob }) {
  return (
    <div className="w-full" role="status" aria-live="polite" aria-label="AI job progress">
      <div className="flex items-center justify-between text-[12px] text-text-secondary mb-1">
        <span>{aiStageLabel(job)}</span>
        <span className="tnum">{job.progress}%</span>
      </div>
      <div className="h-1.5 rounded-full bg-surface-container overflow-hidden">
        <div className={`h-full rounded-full transition-all ${job.status === 'retrying' ? 'bg-amber-500' : 'bg-ai-accent'}`} style={{ width: `${Math.max(job.progress, 4)}%` }} />
      </div>
      {job.status === 'retrying' && job.errorMessage && <p className="text-[11px] text-text-tertiary mt-1">{job.errorMessage}</p>}
    </div>
  );
}

/** Provider status: disabled state explains that deterministic analytics still work. */
export function AiStatusNotice() {
  const status = useQuery('ai:status', aiService.status, { isEmpty: () => false });
  if (status.status === 'loading') return <Skeleton className="h-10" />;
  if (status.error || !status.data) return <Notice tone="warning" title="AI status unavailable">{status.error?.message ?? 'Could not load the AI configuration.'}</Notice>;
  const s = status.data;
  if (!s.enabled) {
    return (
      <Notice tone="info" title="AI analysis is not configured on this server">
        The metrics and comparisons below are computed directly from the database and remain available. An administrator can enable AI insights by setting <code>AI_PROVIDER</code>, <code>AI_MODEL</code> and <code>AI_API_KEY</code> in <code>backend/.env</code>.
      </Notice>
    );
  }
  return (
    <p className="text-[12px] text-text-tertiary flex flex-wrap gap-x-3 gap-y-0.5">
      <span>AI provider: {s.provider} · {s.model}</span>
      <span>Usage this month: {formatNumber(s.usage.tokensMonth)} tokens{s.limits.monthlyTokens ? ` of ${formatNumber(s.limits.monthlyTokens)}` : ''}</span>
      <span>{s.usage.requestsMonth} requests ({s.usage.failuresMonth} failed)</span>
      <span title={s.limitsNote}>Limits are enforced by InstaBoard, not by the provider.</span>
    </p>
  );
}

export function EvidenceTable({ evidence }: { evidence: EvidenceFact[] }) {
  return (
    <div className="overflow-x-auto custom-scrollbar">
      <table className="w-full text-left border-collapse min-w-[760px] text-body-sm">
        <thead>
          <tr className="border-b border-border-strong text-text-secondary font-label-code text-label-code uppercase tracking-wider">
            <th className="py-2 px-2">Ref</th>
            <th className="py-2 px-2">Metric</th>
            <th className="py-2 px-2 text-right">Value</th>
            <th className="py-2 px-2">Period</th>
            <th className="py-2 px-2 text-right">Sample</th>
            <th className="py-2 px-2">Source</th>
          </tr>
        </thead>
        <tbody className="divide-y divide-border-subtle">
          {evidence.map((f) => (
            <tr key={f.id} className={f.sufficient ? undefined : 'bg-amber-50/40'}>
              <td className="py-2 px-2 font-mono text-[12px] text-text-tertiary">{f.id}</td>
              <td className="py-2 px-2">
                <div className="font-semibold text-text-primary">{f.label}</div>
                <div className="text-[11px] text-text-tertiary">{f.kind === 'measured' ? 'Measured' : f.kind === 'calculated' ? 'Calculated' : 'Comparison'} · {f.definition}</div>
                {!f.sufficient && <div className="text-[11px] text-amber-800 mt-0.5">Insufficient data{f.note ? `: ${f.note}` : ''}</div>}
              </td>
              <td className="py-2 px-2 text-right tnum font-semibold">{f.display}</td>
              <td className="py-2 px-2 whitespace-nowrap text-[12px]">{f.periodStart} → {f.periodEnd}</td>
              <td className="py-2 px-2 text-right tnum text-[12px]">{f.sampleSize}{f.missing ? ` (+${f.missing} missing)` : ''}</td>
              <td className="py-2 px-2 text-[12px]">{sourceLabel[f.source] ?? f.source}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
