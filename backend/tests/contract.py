"""Helpers for comparing API responses with the frontend demo-mode payloads.

``fixtures/contract_expected.json`` is generated by ``npm run export:demo-data`` in frontend/: for
every service call it records what demo mode returns, keyed by the API path the same call uses in
api mode. If the seeded API returns the same JSON, the UI renders identically in both modes.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

FIXTURE = Path(__file__).parent / "fixtures" / "contract_expected.json"

# Lists whose order the frontend does not depend on (it sorts them client-side).
UNORDERED = {"/reports": "id"}


def load_contract() -> dict[str, Any]:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def normalize(path: str, value: Any) -> Any:
    key = UNORDERED.get(path)
    if key and isinstance(value, list):
        return sorted(value, key=lambda item: item[key])
    return value


def diff(actual: Any, expected: Any, where: str = "$") -> list[str]:
    """Structural JSON diff; ints and floats with equal value are equal (JSON has one number type)."""
    numeric = (int, float)
    if isinstance(actual, numeric) and isinstance(expected, numeric) and not isinstance(actual, bool) and not isinstance(expected, bool):
        return [] if actual == expected else [f"{where}: {actual!r} != {expected!r}"]
    if type(actual) is not type(expected):
        return [f"{where}: {type(actual).__name__} != {type(expected).__name__}"]
    if isinstance(actual, dict):
        problems: list[str] = []
        for key in sorted(set(actual) | set(expected)):
            if key not in actual:
                problems.append(f"{where}.{key}: missing from API response")
            elif key not in expected:
                problems.append(f"{where}.{key}: unexpected key in API response")
            else:
                problems += diff(actual[key], expected[key], f"{where}.{key}")
        return problems
    if isinstance(actual, list):
        if len(actual) != len(expected):
            return [f"{where}: length {len(actual)} != {len(expected)}"]
        return [p for i, (a, e) in enumerate(zip(actual, expected)) for p in diff(a, e, f"{where}[{i}]")]
    return [] if actual == expected else [f"{where}: {str(actual)[:80]!r} != {str(expected)[:80]!r}"]
